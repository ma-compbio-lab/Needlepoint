"""Source and environment provenance shared by all pipeline stages."""

from __future__ import annotations

import hashlib
import importlib.metadata
import json
import os
import platform
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Iterable

from needlepoint import __version__


def file_sha256(path: str | Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def source_tree_sha256(root: str | Path) -> str:
    """Hash portable package source/resources, excluding generated bytecode."""
    root = Path(root)
    digest = hashlib.sha256()
    paths = sorted(p for p in root.rglob('*')
                   if p.is_file() and p.suffix in ('.py', '.toml'))
    if not paths:
        raise ValueError(f'No package source found under {root}')
    for path in paths:
        digest.update(str(path.relative_to(root)).encode())
        digest.update(b'\0')
        digest.update(bytes.fromhex(file_sha256(path)))
    return digest.hexdigest()


def _git(repo: Path, *args: str) -> str | None:
    completed = subprocess.run(
        ["git", "-C", str(repo), *args],
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.DEVNULL,
        text=True,
    )
    return completed.stdout.strip() if completed.returncode == 0 else None


def source_provenance(
    repo_root: str | Path,
    source_files: Iterable[str | Path] = (),
) -> dict:
    """Capture Git state and exact hashes of files used by a run."""

    repo = Path(repo_root).resolve()
    status = _git(repo, "status", "--porcelain=v1", "--untracked-files=all")
    files = []
    for raw_path in source_files:
        path = Path(raw_path).resolve()
        try:
            label = str(path.relative_to(repo))
        except ValueError:
            label = str(path)
        files.append({"path": label, "sha256": file_sha256(path)})
    return {
        "package": "needlepoint",
        "package_version": __version__,
        "repository": str(repo),
        "git_commit": _git(repo, "rev-parse", "HEAD"),
        "git_branch": _git(repo, "branch", "--show-current"),
        "git_dirty": bool(status),
        "git_status_sha256": hashlib.sha256((status or "").encode()).hexdigest(),
        "source_files": sorted(files, key=lambda item: item["path"]),
    }


def environment_provenance(packages: Iterable[str] = ()) -> dict:
    versions: dict[str, str | None] = {}
    for name in sorted(set(packages)):
        try:
            versions[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            versions[name] = None
    return {
        "python": sys.version,
        "executable": sys.executable,
        "platform": platform.platform(),
        "packages": versions,
    }


def write_json_atomic(path: str | Path, value: dict, *, overwrite: bool = False) -> None:
    """Write a manifest atomically, refusing accidental replacement by default."""

    destination = Path(path)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if destination.exists() and not overwrite:
        raise FileExistsError(f"Refusing to overwrite existing manifest: {destination}")
    descriptor, temporary_name = tempfile.mkstemp(
        prefix=f".{destination.name}.", suffix=".tmp", dir=destination.parent
    )
    temporary = Path(temporary_name)
    try:
        with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
            json.dump(value, handle, indent=2, sort_keys=True)
            handle.write("\n")
            handle.flush()
            os.fsync(handle.fileno())
        if overwrite:
            os.replace(temporary, destination)
        else:
            # Same-filesystem hard-link creation is atomic and fails with
            # FileExistsError if another writer wins after the early check.
            os.link(temporary, destination)
            temporary.unlink()
    finally:
        if temporary.exists():
            temporary.unlink()
